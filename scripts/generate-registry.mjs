import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export function validateManifest(app) {
  if (!/^[a-z][a-z0-9-]*$/.test(app.id ?? "")) throw new Error("Invalid application ID");
  for (const field of ["name", "category", "monogram", "artwork", "tagline", "version", "sourceUrl"]) {
    if (typeof app[field] !== "string" || !app[field].trim()) throw new Error(app.id + ": missing " + field);
  }
  if (!Number.isInteger(app.order) || !app.employee?.role || !app.employee?.instructions) throw new Error(app.id + ": invalid employee");
  if (!/^#[0-9a-f]{6}$/i.test(app.color) || !Array.isArray(app.capabilities) || !Array.isArray(app.formats?.native)) throw new Error(app.id + ": invalid presentation or formats");
  for (const field of ["editor", "workstation"]) {
    if (!["pending", "verified"].includes(app[field]?.status)) throw new Error(app.id + ": invalid " + field + " status");
    if (app[field].status === "verified" && !app[field].release) throw new Error(app.id + ": verified integration must pin a release");
  }
  if (!["pending", "verified"].includes(app.formats.verification)) throw new Error(app.id + ": invalid formats status");
  if (!app.editor.adapterVersion) throw new Error(app.id + ": missing adapter version");
  if (app.editor.status === "verified" && !app.editor.bundleUrl) throw new Error(app.id + ": missing editor bundle");
  if (app.workstation.status === "verified" && !app.workstation.template) throw new Error(app.id + ": missing template");
  const pinnedTemplate = value => typeof value === "string" && /^robyn-[a-z0-9-]+@[1-9][0-9]*$/.test(value);
  const imageDigest = value => typeof value === "string" && /^sha256:[0-9a-f]{64}$/.test(value);
  if (app.workstation.status === "verified" && (!pinnedTemplate(app.workstation.template) || !imageDigest(app.workstation.release))) {
    throw new Error(app.id + ": verified workstation must pin a template revision and image digest");
  }
  if (app.workstation.previousReleases !== undefined) {
    if (!Array.isArray(app.workstation.previousReleases)) throw new Error(app.id + ": invalid previous workstation releases");
    const templates = new Set([app.workstation.template]);
    for (const release of app.workstation.previousReleases) {
      if (!release || typeof release !== "object" || !pinnedTemplate(release.template) || !imageDigest(release.release)) {
        throw new Error(app.id + ": invalid previous workstation release");
      }
      if (templates.has(release.template)) throw new Error(app.id + ": duplicate workstation template revision");
      templates.add(release.template);
    }
  }
  return app;
}

export function readManifests(directory) {
  const files = fs.readdirSync(directory).filter(file => file.endsWith(".json"));
  const entries = files.map(file => ({ file, app: validateManifest(JSON.parse(fs.readFileSync(path.join(directory, file), "utf8"))) }));
  const ids = new Set();
  for (const { app } of entries) {
    if (ids.has(app.id)) throw new Error("Duplicate application ID: " + app.id);
    ids.add(app.id);
  }
  return entries.sort((a, b) => a.app.order - b.app.order || a.app.id.localeCompare(b.app.id));
}

export function generateRegistry(directory, output) {
  const entries = readManifests(directory);
  const imports = entries.map(({ file }, i) => 'import app' + i + ' from "./' + file + '";');
  const content = [
    "// Generated by scripts/generate-registry.mjs. Add application JSON modules; do not edit this file.",
    'import type { StudioAppManifest } from "../manifest";',
    ...imports,
    "",
    "export const studioApps: readonly StudioAppManifest[] = [",
    ...entries.map((_, i) => "  app" + i + " as StudioAppManifest,"),
    "];",
    "",
  ].join("\n");
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== content) fs.writeFileSync(output, content);
  return entries.length;
}

