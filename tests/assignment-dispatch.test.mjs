import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {randomUUID,createHash} from 'node:crypto';
import {PGlite} from '@electric-sql/pglite';

test('workflow retries cannot redispatch, replace a response, bypass cancellation, or release an uncertain employee',async()=>{
  const db=new PGlite();
  const scalar=async(sql,args=[])=>(await db.query(sql,args)).rows[0]?.result;
  try{
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create table auth.users(id uuid primary key,email text);
      create function auth.uid() returns uuid language sql stable as 'select null::uuid';
      grant usage on schema auth to service_role; grant select on auth.users to service_role;
      alter default privileges in schema public grant all on tables to anon,authenticated,service_role;
      create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint);
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text references storage.buckets(id),name text);
      alter table storage.objects enable row level security; grant usage on schema storage to anon,authenticated,service_role;
      grant all on storage.objects to anon,authenticated,service_role;`);
    const migrations=(await fs.readdir(new URL('../supabase/migrations',import.meta.url))).filter(x=>x.endsWith('.sql')).sort();
    for(const name of migrations)await db.exec(await fs.readFile(new URL('../supabase/migrations/'+name,import.meta.url),'utf8'));
    const functions=['bind_studio_assignment_workflow','claim_studio_assignment_dispatch','record_studio_assignment_response','mark_studio_dispatch_uncertain','finish_studio_assignment','record_studio_assignment_terminal_history','claim_studio_employee_provision','claim_studio_employee_creation','bind_studio_employee_instance','ready_studio_employee','review_studio_assignment','replace_studio_assignment_workflow'];
    for(const role of ['anon','authenticated']){
      const permissions=await db.query('select proname,has_function_privilege($1,oid,\'EXECUTE\') as allowed from pg_proc where proname=any($2)',[role,functions]);
      assert.equal(permissions.rows.length,functions.length);
      assert.ok(permissions.rows.every(row=>!row.allowed));
    }
    const owner=randomUUID(),outsider=randomUUID();
    await db.query('insert into auth.users(id) values($1),($2)',[owner,outsider]);
    await db.exec('set role service_role');
    const profiles=[{key:'testcraft',kind:'specialist',appId:'testcraft',role:'Test artist',version:'0.1.0',instructions:'Create native work.'}];
    const workspace=await scalar('select initialize_studio($1,$2) as result',[owner,JSON.stringify(profiles)]);
    const employee=await scalar('select id as result from studio_employees where workspace_id=$1',[workspace]);
    await db.query('insert into agents(workspace_id,agent37_id) values($1,$2)',[workspace,'dispatch-test-instance']);
    await db.query("update studio_employees set instance_id='dispatch-test-instance',provision_state='ready' where id=$1",[employee]);
    const project=await scalar("insert into studio_projects(workspace_id,created_by,name) values($1,$2,'Dispatch proof') returning id as result",[workspace,owner]);
    const create=()=>scalar('select create_studio_assignment($1,$2,$3,$4,$5,$6,$7) as result',[workspace,owner,project,employee,randomUUID(),'Make editable work.','[]']);
    const bind=(job,workflow,user=owner)=>scalar('select bind_studio_assignment_workflow($1,$2,$3,$4) as result',[workspace,user,job.id,workflow]);
    const claim=job=>scalar('select claim_studio_assignment($1,$2,$3) as result',[workspace,owner,job.id]);
    const first=await create(),queued=await create();
    const workflow='workflow-one',duplicate='workflow-two';
    const winners=await Promise.all([bind(first,workflow),bind(first,duplicate)]);
    assert.deepEqual(winners,[true,false]);
    assert.equal(await bind(first,workflow),true);
    await assert.rejects(bind(first,workflow,outsider),/not found/);
    assert.equal(await bind(queued,'workflow-next'),true);
    const running=(await claim(first)).assignment;
    const fence=[workspace,owner,first.id,workflow,running.run_attempt];
    const dispatch=(args=fence)=>scalar('select claim_studio_assignment_dispatch($1,$2,$3,$4,$5) as result',args);
    assert.equal(await dispatch([...fence.slice(0,3),duplicate,running.run_attempt]),false);
    assert.equal(await dispatch([...fence.slice(0,4),randomUUID()]),false);
    assert.equal(await dispatch(),true);
    assert.equal(await dispatch(),false);
    const uncertain=()=>scalar('select mark_studio_dispatch_uncertain($1,$2,$3,$4,$5) as result',fence);
    assert.equal(await uncertain(),true);
    assert.equal(await dispatch(),false,'a lost acknowledgement never permits another POST');
    const finish=(response,outcome='completed',args=fence)=>scalar('select finish_studio_assignment($1,$2,$3,$4,$5,$6,$7,$8,$9) as result',[...args,response,outcome,'Employee result',null]);
    assert.equal(await finish(null,'failed'),null,'unknown dispatch remains occupied');
    assert.equal((await claim(queued)).claimed,false);
    const acknowledge=(session,response)=>scalar('select record_studio_assignment_response($1,$2,$3,$4,$5,$6,$7) as result',[...fence,session,response]);
    assert.equal(await acknowledge(randomUUID(),'response-one'),false);
    assert.equal(await acknowledge(running.session_id,'response-one'),true);
    assert.equal(await acknowledge(running.session_id,'response-one'),true);
    assert.equal(await acknowledge(running.session_id,'response-two'),false);
    assert.equal(await uncertain(),false,'late transport errors cannot downgrade an acknowledged response');
    assert.equal(await finish('response-two'),null);
    const token=createHash('sha256').update(randomUUID()).digest('hex');
    await db.query("insert into studio_employee_tokens(assignment_id,instance_id,token_hash,expires_at) values($1,'dispatch-test-instance',$2,now()+interval '1 hour')",[first.id,token]);
    assert.equal((await scalar('select studio_employee_scope($1) as result',[token])).assignmentId,first.id);
    await scalar('select cancel_studio_assignment($1,$2,$3) as result',[workspace,owner,first.id]);
    await assert.rejects(scalar('select studio_employee_scope($1) as result',[token]),/access denied/);
    assert.equal((await claim(queued)).claimed,false,'cancelling keeps the employee serialized');
    assert.equal(await acknowledge(running.session_id,'response-one'),true,'a late acknowledgement remains available for cancellation');
    const finished=await finish('response-one');
    assert.equal(finished.state,'cancelled','cancellation wins over a late successful response');
    assert.equal(finished.dispatch_state,'finished');
    assert.deepEqual(await finish('response-one'),finished);
    assert.equal(await finish('response-one','completed',[...fence.slice(0,4),randomUUID()]),null);
    const next=(await claim(queued)).assignment;
    assert.equal(next.state,'running');
    assert.ok(next.employee_generation>running.employee_generation,'workstation setup generations advance across serialized jobs');
    const nextFence=[workspace,owner,next.id,'workflow-next',next.run_attempt];
    assert.equal(await dispatch(nextFence),true);
    assert.equal(await scalar('select record_studio_assignment_response($1,$2,$3,$4,$5,$6,$7) as result',[...nextFence,next.session_id,'response-next']),true);
    const empty=await finish('response-next','completed',nextFence);
    assert.equal(empty.state,'failed');assert.equal(empty.error_code,'no_committed_deliverable');
    const delivered=await create();await bind(delivered,'workflow-delivered');
    const deliveredRun=(await claim(delivered)).assignment;
    const deliveredFence=[workspace,owner,delivered.id,'workflow-delivered',deliveredRun.run_attempt];
    assert.equal(await dispatch(deliveredFence),true);
    await scalar('select record_studio_assignment_response($1,$2,$3,$4,$5,$6,$7) as result',[...deliveredFence,deliveredRun.session_id,'response-delivered']);
    const deliveredToken=createHash('sha256').update(randomUUID()).digest('hex');
    await db.query("insert into studio_employee_tokens(assignment_id,instance_id,token_hash,expires_at) values($1,'dispatch-test-instance',$2,now()+interval '1 hour')",[delivered.id,deliveredToken]);
    const asset=await scalar('select employee_create_asset($1,$2,$3) as result',[deliveredToken,randomUUID(),'Delivered native work']);
    const pkg={files:[{path:'edit.native',role:'master',mimeType:'application/octet-stream',bytes:32,sha256:'a'.repeat(64)}],dependencies:[],message:'Created by employee'};
    const revision=await scalar('select employee_begin_revision($1,$2,$3,$4,$5) as result',[deliveredToken,randomUUID(),asset.assetId,null,JSON.stringify(pkg)]);
    const verified=await scalar("select jsonb_agg(jsonb_build_object('id',id,'bytes',bytes)) as result from studio_package_files where revision_id=$1",[revision.revisionId]);
    await scalar('select employee_commit_revision($1,$2,$3) as result',[deliveredToken,revision.revisionId,JSON.stringify(verified)]);
    assert.equal((await finish('response-delivered','completed',deliveredFence)).state,'awaiting_review');
    await assert.rejects(scalar('select studio_employee_scope($1) as result',[deliveredToken]),/access denied/);
    const lost=await create();await bind(lost,'workflow-lost');
    const lostRun=(await claim(lost)).assignment;
    const lostFence=[workspace,owner,lost.id,'workflow-lost',lostRun.run_attempt];
    assert.equal(await dispatch(lostFence),true);
    assert.equal(await finish(null,'completed',lostFence),null,'no response ID and no transcript evidence stays unresolved');
    assert.equal(await scalar('select record_studio_assignment_terminal_history($1,$2,$3,$4,$5,$6) as result',[...lostFence,'other-session']),false);
    assert.equal(await scalar('select record_studio_assignment_terminal_history($1,$2,$3,$4,$5,$6) as result',[workspace,outsider,...lostFence.slice(2),lostRun.session_id]),false);
    assert.equal(await scalar('select record_studio_assignment_terminal_history($1,$2,$3,$4,$5,$6) as result',[...lostFence,lostRun.session_id]),true);
    assert.equal((await finish(null,'completed',lostFence)).error_code,'no_committed_deliverable','transcript recovery still requires a real deliverable');
    await scalar('select initialize_studio($1,$2) as result',[owner,JSON.stringify([{...profiles[0],key:'workstation-test'}])]);
    const provisionEmployee=await scalar("select id as result from studio_employees where workspace_id=$1 and employee_key='workstation-test'",[workspace]);
    const provisionArgs=[workspace,owner,provisionEmployee];
    const provision=await scalar('select claim_studio_employee_provision($1,$2,$3) as result',provisionArgs);
    assert.ok(provision.provision_attempt);
    assert.equal((await scalar('select claim_studio_employee_provision($1,$2,$3) as result',provisionArgs)).provision_attempt,provision.provision_attempt);
    await assert.rejects(scalar('select claim_studio_employee_provision($1,$2,$3) as result',[workspace,outsider,provisionEmployee]),/not found/);
    const createArgs=[...provisionArgs,provision.provision_attempt];
    assert.deepEqual(await Promise.all([1,2].map(()=>scalar('select claim_studio_employee_creation($1,$2,$3,$4) as result',createArgs))),[true,false]);
    const bindInstance=(instance,attempt=provision.provision_attempt)=>scalar('select bind_studio_employee_instance($1,$2,$3,$4,$5,$6,$7) as result',[...provisionArgs,attempt,instance,'pinned-test@1',JSON.stringify({cpu:2,memory:4,disk:6})]);
    assert.equal(await bindInstance('workstation-test',randomUUID()),false);
    const outsiderWorkspace=await scalar('select initialize_studio($1,$2) as result',[outsider,'[]']);
    await db.query('insert into agents(agent37_id,workspace_id) values($1,$2)',['foreign-workstation',outsiderWorkspace]);
    await assert.rejects(bindInstance('foreign-workstation'),/not found/);
    assert.equal(await bindInstance('workstation-test'),true);
    assert.equal(await bindInstance('workstation-test'),true);
    assert.equal(await bindInstance('another-workstation'),false);
    assert.equal(await scalar('select ready_studio_employee($1,$2,$3,$4) as result',[...provisionArgs,'wrong-instance']),false);
    assert.equal(await scalar('select ready_studio_employee($1,$2,$3,$4) as result',[...provisionArgs,'workstation-test']),true);
    const recoverable=await create();await bind(recoverable,'workflow-interrupted');
    const interrupted=(await claim(recoverable)).assignment;
    const oldFence=[workspace,owner,recoverable.id,'workflow-interrupted',interrupted.run_attempt];
    assert.equal(await dispatch(oldFence),true);
    const replace=workflow=>scalar('select replace_studio_assignment_workflow($1,$2,$3,$4,$5) as result',[workspace,owner,recoverable.id,'workflow-interrupted',workflow]);
    await assert.rejects(scalar('select replace_studio_assignment_workflow($1,$2,$3,$4,$5) as result',[workspace,outsider,recoverable.id,'workflow-interrupted','foreign-worker']),/not found/);
    assert.deepEqual(await Promise.all([replace('workflow-recovery'),replace('workflow-racing')]),[true,false]);
    assert.equal(await replace('workflow-recovery'),true,'replacement retry is idempotent');
    const recovered=(await claim(recoverable)).assignment;
    assert.equal(recovered.session_id,interrupted.session_id);
    assert.equal(recovered.run_attempt,interrupted.run_attempt);
    assert.equal(recovered.employee_generation,interrupted.employee_generation);
    const newFence=[workspace,owner,recoverable.id,'workflow-recovery',interrupted.run_attempt];
    assert.equal(await dispatch(newFence),false,'replacement cannot resend a claimed turn');
    assert.equal(await finish(null,'failed',oldFence),null,'delayed old worker cannot finish the replacement');
    await scalar('select cancel_studio_assignment($1,$2,$3) as result',[workspace,owner,recoverable.id]);
    assert.equal(await scalar('select record_studio_assignment_response($1,$2,$3,$4,$5,$6,$7) as result',[...newFence,recovered.session_id,'recovered-response']),true);
    assert.equal((await finish('recovered-response','completed',newFence)).state,'cancelled');
    const idle=await create();await bind(idle,'workflow-idle');
    const idleRun=(await claim(idle)).assignment;
    const cancelledIdle=await scalar('select cancel_studio_assignment($1,$2,$3) as result',[workspace,owner,idle.id]);
    assert.equal(cancelledIdle.state,'cancelled','an idle workstation needs no live worker to cancel');
    assert.equal(cancelledIdle.dispatch_state,'finished');
    assert.equal(await dispatch([workspace,owner,idle.id,'workflow-idle',idleRun.run_attempt]),false);
    const archived=await create();await bind(archived,'workflow-archived');
    const archivedRun=(await claim(archived)).assignment;
    await db.query("update studio_projects set status='archived' where id=$1",[project]);
    const archivedFence=[workspace,owner,archived.id,'workflow-archived',archivedRun.run_attempt];
    assert.equal(await dispatch(archivedFence),false);
    assert.equal((await finish(null,'failed',archivedFence)).state,'failed');
    await db.query("update studio_projects set status='active' where id=$1",[project]);
    const reviewRequest=randomUUID();
    const reviewArgs=[workspace,owner,delivered.id,reviewRequest,'changes_requested','Preserve the layout; revise the heading.'];
    const reviewed=await scalar('select review_studio_assignment($1,$2,$3,$4,$5,$6) as result',reviewArgs);
    assert.ok(reviewed.followup_assignment_id);
    assert.deepEqual(await scalar('select review_studio_assignment($1,$2,$3,$4,$5,$6) as result',reviewArgs),reviewed,'lost review acknowledgement does not create another continuation');
    await assert.rejects(scalar('select review_studio_assignment($1,$2,$3,$4,$5,$6) as result',[workspace,outsider,...reviewArgs.slice(2)]),/not found/);
    await assert.rejects(scalar('select review_studio_assignment($1,$2,$3,$4,$5,$6) as result',[...reviewArgs.slice(0,3),randomUUID(),'approved','']),/review already recorded/);
    const exactInput=await db.query('select asset_id,revision_id from studio_assignment_inputs where assignment_id=$1',[reviewed.followup_assignment_id]);
    assert.deepEqual(exactInput.rows,[{asset_id:asset.assetId,revision_id:revision.revisionId}]);
    assert.equal(await scalar('select employee_id as result from studio_assignments where id=$1',[reviewed.followup_assignment_id]),employee);
    await db.query("update studio_assignments set state='awaiting_review' where id=$1",[reviewed.followup_assignment_id]);
    const approved=await scalar('select review_studio_assignment($1,$2,$3,$4,$5,$6) as result',[workspace,owner,reviewed.followup_assignment_id,randomUUID(),'approved','']);
    assert.equal(approved.followup_assignment_id,null);
    assert.equal(await scalar('select state as result from studio_assignments where id=$1',[reviewed.followup_assignment_id]),'completed');
    await db.exec('reset role');
    await db.exec(await fs.readFile(new URL('../supabase/migrations/0007_assignment_dispatch.sql',import.meta.url),'utf8'));
    await db.exec(await fs.readFile(new URL('../supabase/migrations/0008_assignment_runner.sql',import.meta.url),'utf8'));
    assert.equal(await scalar('select response_id as result from studio_assignments where id=$1',[first.id]),'response-one');
  }finally{await db.close();}
});
